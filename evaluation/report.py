"""REPORT_RESULTS.md from results/*.json only. No number is typed in here: tables, statuses and provenance come from
the result files; this module only lays them out."""
import json
from pathlib import Path

ORDER = [("x1_detection", "X1"), ("x2_tracking", "X2"), ("x3_rules", "X3"), ("x4_impact", "X4"), ("x5_vlm", "X5"),
         ("x6_crosscamera", "X6"), ("x7_grounding", "X7"), ("optimize", "OPT")]

THREATS = [
    "Single camera, single day. Every 'measured on Dhaka' number comes from one fixed camera (clip 20261025_092449_side1_1.mp4 "
    "or the footage named in its source line); nothing here is shown to hold at another site, hour or weather.",
    "Synthetic is not Dhaka. Rule decisions from tools/bench_accuracy.py, the impact check against simulated delay and the signal "
    "results come from simulators the team wrote; they test the code against the team's own model of traffic, so they can "
    "confirm a mechanism works but not that it matches the street.",
    "Tiny counts. The simulated rule benchmark has 2-6 true events per rule; a single miss moves recall by 17-50 points. "
    "No confidence intervals are given where n is this small.",
    "Proxy tracking is not accuracy. Without ground-truth tracks, ByteTrack and BoT-SORT can be compared only on cost, track "
    "counts and lengths and mutual agreement. Fewer or longer tracks may reflect merged identities rather than better tracking.",
    "Timings were taken on a shared 6-core/12-thread laptop CPU (i5-11400H, no GPU) and may have been taken while other jobs ran; "
    "the load average is recorded beside each timing. Treat them as indicative to within a factor, not as benchmarks.",
    "External numbers (CityFlowV2) are US traffic, copied from the notebook's printed output in research/cityflow/README.md, not "
    "re-run here, and do not predict Dhaka performance; the within-camera Dhaka check cannot see viewpoint change.",
    "Hand labels are the ground truth for everything marked 'needs': their quality (one labeller, boundary ambiguity of "
    "'when a violation starts') bounds every number that will eventually be reported. docs/EVALUATION.md asks for two raters on "
    "the subjective items.",
    "Training/test separation: none of the detector's training split is recorded in the repository, so held-out status of "
    "any labelled Dhaka set must be established by the team before X1 is reported.",
]


def _cat(status):
    s = status.lower()
    for k in ("measured on dhaka", "synthetic", "external", "proxy"):
        if s.startswith(k):
            return k
    return status


def _cell(v):
    return str(v).replace("|", "\\|").replace("\n", " ")


def _table_md(t):
    out = [f"**{t['title']}**", "", "| " + " | ".join(t["columns"]) + " |", "|" + "---|" * len(t["columns"])]
    out += ["| " + " | ".join(_cell(c) for c in r) + " |" for r in t["rows"]]
    out += ["", f"*Provenance: {t['source']}*", ""]
    return out


def write(results_dir, out_path):
    results_dir = Path(results_dir)
    L = ["# Chapter 4 - Results (generated)", "",
         "Generated by `tools/evaluate.py report` from `results/*.json` only. Every figure below was either produced by the "
         "command named in the line under its table, or copied from the named repository file. Status labels: **measured on "
         "Dhaka** (real Dhaka footage, with ground truth or as stated), **synthetic** (simulator or scripted scenario), "
         "**external** (published/third-party benchmark), **not measured - needs ...** (no ground truth exists yet; no number is given).", ""]
    loaded = []
    for stem, tag in ORDER:
        p = results_dir / f"{stem}.json"
        loaded.append((tag, json.loads(p.read_text()) if p.exists() else None))
    L += ["## Summary", "", "| Item | What | Real numbers now | Still needs data |", "|---|---|---|---|"]
    for tag, d in loaded:
        if d is None:
            L.append(f"| {tag} | not run | - | run `tools/evaluate.py` |")
            continue
        sts = sorted({_cat(str(r[-1])) for t in d["tables"] for r in t["rows"]})
        L.append(f"| {tag} | {d['title']} | {len(d['tables'])} table(s): {'; '.join(sts) or '-'} | "
                 f"{len(d['needs'])} item(s)" + (": " + "; ".join(n['what'] for n in d['needs']) if d["needs"] else "") + " |")
    L.append("")
    for tag, d in loaded:
        if d is None:
            continue
        L += [f"## {tag}. {d['title']}", ""]
        for t in d["tables"]:
            L += _table_md(t)
        if d["needs"]:
            L += ["**Not measured**", "", "| Quantity | Status |", "|---|---|"]
            L += [f"| {_cell(n['what'])} | {_cell(n['status'])} |" for n in d["needs"]]
            L.append("")
        for n in d["notes"]:
            L.append(f"- {n}")
        if d["notes"]:
            L.append("")
        pv = d["provenance"]
        L += [f"*Result file: `results/{d['item']}.json`; harness commit {pv['git_commit']}; produced {pv['timestamp_utc']} "
              f"by `{pv['command']}`.*", ""]
    L += ["## Threats to validity", ""] + [f"{i}. {t}" for i, t in enumerate(THREATS, 1)] + [""]
    Path(out_path).write_text("\n".join(L))
    print(f"wrote {out_path}")
